CREATE TABLE aplicacion_insumo (
    id BIGINT NOT NULL AUTO_INCREMENT,
    lote_campania_id BIGINT NOT NULL,
    insumo_id BIGINT NOT NULL,
    fecha DATE NOT NULL,
    cantidad DECIMAL(14,4) NOT NULL,
    unidad_medida VARCHAR(20) NOT NULL,
    precio_unitario_importe DECIMAL(15,4) NOT NULL,
    precio_unitario_moneda VARCHAR(3) NOT NULL,
    precio_unitario_tipo_cambio DECIMAL(12,6) NOT NULL,
    precio_unitario_importe_usd DECIMAL(15,4) NOT NULL,
    costo_total_importe DECIMAL(15,4) NOT NULL,
    costo_total_moneda VARCHAR(3) NOT NULL,
    costo_total_tipo_cambio DECIMAL(12,6) NOT NULL,
    costo_total_importe_usd DECIMAL(15,4) NOT NULL,
    comentarios TEXT,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    created_by VARCHAR(100),
    PRIMARY KEY (id),
    INDEX idx_aplicacion_insumo_fecha (lote_campania_id, fecha),
    CONSTRAINT fk_ai_lote_campania FOREIGN KEY (lote_campania_id) REFERENCES lote_campania (id),
    CONSTRAINT fk_ai_insumo FOREIGN KEY (insumo_id) REFERENCES insumo (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE tarea (
    id BIGINT NOT NULL AUTO_INCREMENT,
    lote_campania_id BIGINT NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    fecha DATE NOT NULL,
    ejecutor VARCHAR(20) NOT NULL,
    proveedor VARCHAR(120),
    modo_costo VARCHAR(20) NOT NULL,
    cantidad DECIMAL(14,4),
    unidad_cantidad VARCHAR(30),
    valor_unitario_importe DECIMAL(15,4) NOT NULL,
    valor_unitario_moneda VARCHAR(3) NOT NULL,
    valor_unitario_tipo_cambio DECIMAL(12,6) NOT NULL,
    valor_unitario_importe_usd DECIMAL(15,4) NOT NULL,
    costo_total_importe DECIMAL(15,4) NOT NULL,
    costo_total_moneda VARCHAR(3) NOT NULL,
    costo_total_tipo_cambio DECIMAL(12,6) NOT NULL,
    costo_total_importe_usd DECIMAL(15,4) NOT NULL,
    comentarios TEXT,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    created_by VARCHAR(100),
    PRIMARY KEY (id),
    INDEX idx_tarea_fecha (lote_campania_id, fecha),
    INDEX idx_tarea_tipo (lote_campania_id, tipo),
    CONSTRAINT fk_tarea_lote_campania FOREIGN KEY (lote_campania_id) REFERENCES lote_campania (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
